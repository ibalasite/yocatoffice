#!/usr/bin/env bash
# scripts/bootstrap-secrets.sh — generate local fake secrets; never commit the output (LOCAL_DEPLOY §3.5).
# Idempotent: ensures the existing yocat-pg Secret, aligns the app DB password to it, and writes secrets.env.
set -euo pipefail

APP_NS="yocat-office-backend-local"
DB_NS="yocat"
SECRETS_DIR="k8s/overlays/local"
SECRETS_ENV="${SECRETS_DIR}/secrets.env"

echo "[bootstrap-secrets] ensure namespace ${APP_NS} / ${DB_NS}"
for ns in "${APP_NS}" "${DB_NS}"; do
  kubectl create namespace "${ns}" --dry-run=client -o yaml | kubectl apply -f -
done

# 1) existing yocat-pg Secret: create if absent (postgres image needs POSTGRES_USER/PASSWORD/DB)
if ! kubectl get secret yocat-pg -n "${DB_NS}" >/dev/null 2>&1; then
  echo "[bootstrap-secrets] yocat-pg Secret missing -> create (user=yocat db=yocat)"
  kubectl create secret generic yocat-pg -n "${DB_NS}" \
    --from-literal=POSTGRES_USER="yocat" \
    --from-literal=POSTGRES_DB="yocat" \
    --from-literal=POSTGRES_PASSWORD="$(openssl rand -hex 32)"
else
  echo "[bootstrap-secrets] reuse existing yocat-pg Secret"
fi

# 2) read DB password so the app secret matches the DB
DB_PASSWORD="$(kubectl get secret yocat-pg -n "${DB_NS}" -o jsonpath='{.data.POSTGRES_PASSWORD}' | base64 -d)"

# 3) write app secrets.env (app namespace; all fake local values)
mkdir -p "${SECRETS_DIR}"
cat > "${SECRETS_ENV}" <<EOF
# AUTO-GENERATED by bootstrap-secrets.sh — local fake values, never commit to git
DB_PASSWORD=${DB_PASSWORD}
SESSION_SIGNING_KEY=$(openssl rand -hex 64)
ENCRYPTION_KEY=$(openssl rand -hex 32)
ADMIN_INIT_PASSWORD=$(openssl rand -base64 16 | tr -dc 'a-zA-Z0-9' | head -c 16)
EOF

echo "[bootstrap-secrets] wrote ${SECRETS_ENV} (gitignored)"
echo "[bootstrap-secrets] local fake passwords; use Sealed Secrets / Vault for real environments"
